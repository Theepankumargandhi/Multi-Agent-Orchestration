def render_evaluation_report(summary, values):
    fields = [
        "dataset",
        "model",
        "version",
        "reviewer",
        "scope",
        "recall",
        "precision",
        "coverage",
        "latency",
        "cost",
        "tokens",
        "families",
        "cases",
        "safety",
        "grounding",
        "memory",
        "cache",
        "routing",
        "verification",
        "abstention",
        "confidence",
        "calibration",
        "integrity",
        "lineage",
        "limitations",
        "errors",
        "timeouts",
        "repairs",
        "fallbacks",
        "decisions",
    ]
    details = [f"{field}: {values.get(field, 'unavailable')}" for field in fields]
    return "\n".join([summary, *details])
